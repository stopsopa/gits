# ---------- the dump script ----------

# One file per call. Everything a script can know is in its arguments and in the GITS* env vars.
# DUMPS (where to write) is exported before every gits command below.
cat <<'EEE' > "${WORK}/dump.sh"
FILE="${DUMPS}/$(printf '%03d' "${GITS_EVENT_SEQ}")-${GITS_EVENT_NAME}-${GITS_EVENT_INDEX}.${GITS_EVENT_TRIGGER}.txt"
mkdir -p "${DUMPS}"
{
  echo "arguments (${#}):"
  for ARGUMENT in "${@}"; do
    echo "  >${ARGUMENT}<"
  done
  echo "working directory: $(pwd)"
  # name by name, sorted: a value can have more than one line (GITS_EVENT_LIST), it stays together
  echo "env, what gits tells the script:"
  for NAME in $(env | grep -oE '^GITS[A-Z0-9_]*' | sort -u); do
    if [[ "${NAME}" == "GITS_EVENT_SCRIPT" || "${!NAME}" != "${GITS_EVENT_SCRIPT}" ]]; then
      printf '%s=%s\n' "${NAME}" "${!NAME}"
    fi
  done
  # the variables which register scripts are in the environment of the script too
  echo "env, registered scripts (all point to this script):"
  for NAME in $(env | grep -oE '^GITS[A-Z0-9_]*' | sort -u); do
    if [[ "${!NAME}" == "${GITS_EVENT_SCRIPT}" && "${NAME}" != "GITS_EVENT_SCRIPT" ]]; then
      printf '%s\n' "${NAME}"
    fi
  done
} > "${FILE}"
EEE

