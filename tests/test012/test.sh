# run <name of the dump directory> <gits arguments...>
# one gits command with its own dump directory, output of gits into <directory>.log
function run {
  export DUMPS="${WORK}/dumps/${1}"
  shift
  gits "${@}" > "${DUMPS}.log" 2>&1
}

# fired <name of the dump directory>
# the events of that run in the order they happened, one per line (from the files written
# through the variable of the event itself)
function fired {
  ls "${WORK}/dumps/${1}" | grep -v '_ALL\.txt$' | sed -E 's/^[0-9]+-(.*)-[0-9]+\..*$/\1/' | paste -sd ' ' -
}

# calls <name of the dump directory>
# how many files: the event's own variable + GITS_<COMMAND>_ALL + GITS_ALL -> 3 per event
function calls {
  local ALL OWN
  ALL="$(ls "${WORK}/dumps/${1}" | wc -l | tr -d ' ')"
  OWN="$(ls "${WORK}/dumps/${1}" | grep -vc '_ALL\.txt$')"
  echo "events: ${OWN}, files: ${ALL}"
}

