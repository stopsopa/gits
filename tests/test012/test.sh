#
# Lifecycle events, part 1: every event of every command is registered, and every call of
# a script is dumped to a file. The dumps stay after the test: this is the place to see what a
# script of a given event really gets.
#
#   tests/test012/tmp/dump.sh                 the script, the same one for every event
#   tests/test012/tmp/dumps/<nn>-<command>/   one directory per gits command executed here
#       <SEQ>-<EVENT>-<INDEX>.<TRIGGER>.txt   one file per call: arguments, working directory,
#                                             every GITS* env var
#
#   SEQ      number of the event in that run (GITS_EVENT_SEQ)
#   EVENT    GITS_EVENT_NAME, e.g. BEFORE_COPY
#   INDEX    which occurrence of that event (GITS_EVENT_INDEX)
#   TRIGGER  the variable which pointed to the script (GITS_EVENT_TRIGGER): the one of the event,
#            GITS_<COMMAND>_ALL or GITS_ALL. All three are registered, so every event has three files.
#
# What is tested, in this order:
#
#   1. registration: every variable which has an example script in events/examples/ is exported,
#      pointing to dump.sh (the replaceable FIND events are left to their default)
#   2. for each command (init, add, diff, isinsync, push --yes with a new, a changed and no change,
#      pull, pull --yes, state, find, url, move, migrate, a command which fails): the exact list
#      of events, in order - that list is the lifecycle of the command, see LIFECYCLE.md
#   3. every event was dumped three times (its own variable, GITS_<COMMAND>_ALL, GITS_ALL)
#   4. what a script sees: the native variables, the numbering, per-file variables, results
#
# The project has one plain and one encrypted element, to reach the DECRYPT / ENCRYPT events.
#
# Needs: the compiled binary (/bin/bash compile.sh), the real encoder process of
# submodules/encrypt with a private ssh-agent (tests/_lib.sh, as tests/test007).
#
# /bin/bash tests/test012/test.sh
#
# Checks are done with function "test" of bash/test.sh, see tests/_lib.sh
#

